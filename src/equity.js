/* ============================================================
 * equity.js — 胜率估算与起手牌排名
 *             Equity estimation and starting-hand ranking
 *
 * 关键概念：
 * Key concepts:
 *   1. 169 类起手牌按强度排名 → 百分位（0 = AA，1 = 32o）
 *   1. The 169 starting-hand classes ranked by strength → percentile (0 = AA, 1 = 32o)
 *      职业选手的"开池范围 top 20%"即百分位 < 0.20
 *      A pro's "top 20% open range" means percentile < 0.20
 *   2. 估算胜率时，对手手牌不再视为"完全随机"，而是限制在给定范围内
 *      —— 否则会把任何两张牌都算成约 1/(n+1) 的胜率，导致过度跟注
 *   2. When estimating equity, opponent hands are no longer treated as "perfectly random" but
 *      restricted to a given range — otherwise any two cards would be valued at roughly 1/(n+1)
 *      equity, causing over-calling.
 * ============================================================ */
(function (global) {
  'use strict';
  const PK = global.PK || (global.PK = {});
  const evaluate = PK.evaluate;

  /* ============================================================
   * 169 类起手牌强度排名（由 test/gen-rank.js 按"对 1 名随机对手的
   * 胜率"以 24000 次蒙特卡洛生成，序号 0 = 最强）
   * 169-class starting-hand strength ranking (generated by test/gen-rank.js from "equity versus
   * one random opponent" over 24000 Monte Carlo trials; index 0 = strongest)
   * ============================================================ */
  const HAND_RANK_ORDER = [
    'AA', 'KK', 'QQ', 'JJ', 'TT', '99', '88', 'AKs', '77', 'AQs', 'AKo', 'AJs',
    'ATs', 'AQo', 'KQs', '66', 'AJo', 'ATo', 'A9s', 'KJs', 'A8s', 'KQo', 'A7s', 'KTs',
    'K9s', 'QJs', 'A9o', '55', 'KJo', 'A8o', 'A5s', 'A6s', 'QTs', 'KTo', 'A4s', 'A7o',
    'A3s', 'K8s', 'K9o', 'A5o', 'QJo', 'JTs', 'K7s', 'Q9s', 'A6o', 'QTo', '44', 'A2s',
    'A4o', 'K6s', 'J9s', 'K8o', 'Q8s', 'A3o', 'Q9o', 'A2o', 'K7o', 'JTo', 'K4s', 'K5s',
    'Q7s', 'J8s', 'K3s', 'K6o', 'T9s', 'J9o', '33', 'Q6s', 'Q5s', 'K2s', 'K5o', 'Q8o',
    'J7s', 'K4o', 'Q7o', 'T8s', 'J8o', 'T9o', 'Q4s', 'K3o', '22', '98s', 'Q3s', 'J6s',
    'K2o', 'T7s', 'Q6o', 'Q2s', 'J5s', 'J7o', 'Q5o', 'T8o', 'Q4o', 'J4s', '97s', 'Q3o',
    'J3s', 'T6s', '87s', 'T7o', '98o', 'J6o', 'Q2o', '96s', 'J5o', 'T5s', 'J2s', 'T4s',
    'J4o', '97o', 'T6o', '86s', '76s', '95s', '87o', 'T3s', 'J3o', '85s', '96o', 'T2s',
    'T5o', 'T4o', 'J2o', '94s', '93s', '75s', '86o', '65s', '84s', '95o', 'T3o', '92s',
    '76o', '85o', '64s', '74s', 'T2o', '54s', '83s', '94o', '82s', '75o', '73s', '93o',
    '65o', '53s', '63s', '84o', '92o', '74o', '43s', '54o', '72s', '52s', '64o', '83o',
    '62s', '82o', '42s', '73o', '63o', '32s', '53o', '43o', '72o', '52o', '62o', '42o',
    '32o',
  ];
  const RANK_N = HAND_RANK_ORDER.length;          // 169
  const rankIdx = new Map();
  HAND_RANK_ORDER.forEach((k, i) => rankIdx.set(k, i));

  /* 52×52 查表：由两张牌直接得到百分位，避免每次做字符串拼接 */
  /* 52×52 lookup table: get the percentile directly from two cards, avoiding string concatenation each time */
  const _pct2 = new Float64Array(52 * 52);
  (function buildPctTable() {
    for (let c1 = 0; c1 < 52; c1++) {
      for (let c2 = 0; c2 < 52; c2++) {
        if (c1 === c2) { _pct2[c1 * 52 + c2] = 1; continue; }
        const i = rankIdx.get(PK.holeKey(c1, c2));
        _pct2[c1 * 52 + c2] = i === undefined ? 1 : i / (RANK_N - 1);
      }
    }
  })();

  /** 两张牌的强度百分位（0 = AA，1 = 32o） */
  /** Strength percentile of two cards (0 = AA, 1 = 32o) */
  function pct2(c1, c2) { return _pct2[c1 * 52 + c2]; }

  /** 起手牌 key 或牌数组 → 百分位 */
  /** Starting-hand key or card array → percentile */
  function handPercentile(holeOrKey) {
    let key;
    if (typeof holeOrKey === 'string') key = holeOrKey;
    else key = PK.holeKey(holeOrKey[0], holeOrKey[1]);
    const i = rankIdx.get(key);
    return i === undefined ? 1 : i / (RANK_N - 1);
  }

  /* ============================================================
   * 蒙特卡洛胜率估算
   * Monte Carlo equity estimation
   * ============================================================ */

  /**
   * 蒙特卡洛胜率估算
   * Monte Carlo equity estimation
   *
   * @param {number[]} hole     自己的 2 张底牌
   * @param {number[]} hole     our own 2 hole cards
   * @param {number[]} board    已知公共牌（0/3/4/5 张）
   * @param {number[]} board    known community cards (0/3/4/5)
   * @param {number}   nOpp     对手数量
   * @param {number}   nOpp     number of opponents
   * @param {number}   iters    模拟次数
   * @param {number}   iters    number of simulations
   * @param {number|object} [range] 对手范围模型。
   * @param {number|object} [range] opponent range model.
   *        传数字   —— 等价于 { rangePct: 数字 }（对手只从该百分位内抽牌）
   *        Pass a number   — equivalent to { rangePct: number } (the opponent draws only within that percentile)
   *        传对象   —— {
   *        Pass an object — {
   *            rangePct  对手翻前范围上限（0~1，1 = 完全随机）
   *            rangePct  opponent preflop range ceiling (0~1, 1 = fully random)
   *            minCat    对手成牌的最低牌型等级（0=任意 1=一对以上 2=两对以上 …）
   *            minCat    minimum hand category for the opponent (0=any, 1=one pair or better, 2=two pair or better, …)
   *            bluffFrac 纯诈唬比例：这部分对手不受 minCat 约束
   *            bluffFrac share of pure bluffs: these opponents are not constrained by minCat
   *        }
   *      "翻后下注 = 手上有东西"这一事实，用 minCat 建模；
   *      否则 AI 会把对手当成随机牌，从而无脑跟注到底。
   *      The fact that "a postflop bet = having something" is modeled with minCat; otherwise the AI would
   *      treat opponents as random hands and call everything down.
   * @returns {number} 0~1 的胜率（平局计半分）
   * @returns {number} equity in 0~1 (a split pot counts as half)
   */
  function estimateEquity(hole, board, nOpp, iters, range) {
    iters = Math.max(1, iters || 1500);
    nOpp = Math.max(1, nOpp | 0);

    let rangePct = 1, minCat = 0, bluffFrac = 1;
    if (typeof range === 'number') rangePct = range;
    else if (range) {
      if (range.rangePct !== undefined) rangePct = range.rangePct;
      if (range.minCat !== undefined) minCat = range.minCat;
      if (range.bluffFrac !== undefined) bluffFrac = range.bluffFrac;
    }
    const restrictRange = rangePct > 0 && rangePct < 1;
    const restrictCat = minCat > 0 && bluffFrac < 1;
    const anyRestrict = restrictRange || restrictCat;

    /* 接受概率越低，需要的重试上限越高（同时设硬上限，保证最坏情况可控） */
    /* The lower the acceptance probability, the higher the retry cap needed (a hard cap is also set so the worst case stays bounded) */
    let acceptP = 1;
    if (restrictRange) acceptP *= rangePct;
    if (restrictCat) acceptP *= (1 - bluffFrac) * 0.55 + bluffFrac;
    const MAX_TRY = anyRestrict ? Math.min(48, Math.ceil(2.2 / Math.max(0.03, acceptP))) : 0;

    const known = new Uint8Array(52);
    for (let i = 0; i < hole.length; i++)  known[hole[i]] = 1;
    for (let i = 0; i < board.length; i++) known[board[i]] = 1;

    const deck = [];
    for (let c = 0; c < 52; c++) if (!known[c]) deck.push(c);

    const nBoardExtra = 5 - board.length;
    const need = nBoardExtra + nOpp * 2;
    const deckLen = deck.length;
    if (need > deckLen) return 0;

    /* 预分配，避免成千上万次数组分配 */
    /* Pre-allocate to avoid thousands of array allocations */
    const full = new Array(5);
    for (let i = 0; i < board.length; i++) full[i] = board[i];
    const myFull = new Array(7);
    myFull[0] = hole[0]; myFull[1] = hole[1];
    const oppFull = new Array(7);

    let win = 0, tieShare = 0;

    for (let it = 0; it < iters; it++) {
      /* 部分 Fisher-Yates：前 need 个位置即为均匀随机抽样 */
      /* Partial Fisher-Yates: the first need positions are an unbiased random sample */
      for (let i = 0; i < need; i++) {
        const j = i + ((Math.random() * (deckLen - i)) | 0);
        const t = deck[i]; deck[i] = deck[j]; deck[j] = t;
      }
      for (let i = 0; i < 5; i++) {
        if (i >= board.length) full[i] = deck[i - board.length];
        myFull[2 + i] = full[i];
      }
      const myScore = evaluate(myFull);

      let best = -1, tied = 0;
      let idx = nBoardExtra;
      for (let k = 0; k < nOpp; k++) {
        let c1 = deck[idx], c2 = deck[idx + 1];
        let s = -1;

        if (anyRestrict) {
          /* 每个对手独立决定"这次是在价值下注还是在诈唬" */
          /* Each opponent independently decides "whether this time it is value-betting or bluffing" */
          const asBluff = restrictCat ? (Math.random() < bluffFrac) : true;
          let tries = 0;
          for (;;) {
            oppFull[0] = c1; oppFull[1] = c2;
            for (let i = 0; i < 5; i++) oppFull[2 + i] = full[i];
            s = evaluate(oppFull);

            const rangeOK = !restrictRange || pct2(c1, c2) <= rangePct;
            const catOK = !restrictCat || asBluff || (s >> 20) >= minCat;
            if ((rangeOK && catOK) || tries >= MAX_TRY) break;

            /* 从"未使用区"换两张牌重抽 */
            /* Redraw two cards from the "unused region" */
            const j = need + ((Math.random() * (deckLen - need)) | 0);
            const t = deck[idx]; deck[idx] = deck[j]; deck[j] = t;
            c1 = deck[idx];
            const j2 = need + ((Math.random() * (deckLen - need)) | 0);
            const t2 = deck[idx + 1]; deck[idx + 1] = deck[j2]; deck[j2] = t2;
            c2 = deck[idx + 1];
            tries++;
          }
        } else {
          for (let i = 0; i < 5; i++) oppFull[2 + i] = full[i];
          oppFull[0] = c1; oppFull[1] = c2;
          s = evaluate(oppFull);
        }

        idx += 2;
        if (s > best) { best = s; tied = 1; }
        else if (s === best) tied++;
      }

      /* 多人池平局按实际平分人数计分：与 t 个对手并列最强时，
         我的份额是 1/(t+1)，而不是固定 0.5（两人平分才等于 0.5，
         四人平分时 0.5 会把平局 EV 高估一倍）。
         Multiway pot splits are scored by the actual number of tied players: when tied for strongest with
         t opponents, my share is 1/(t+1), not a fixed 0.5 (0.5 only equals a two-way split; with a
         four-way split, 0.5 doubles the tie EV). */
      if (myScore > best) win++;
      else if (myScore === best) tieShare += 1 / (tied + 1);
    }

    return (win + tieShare) / iters;
  }

  /* ---------------- 翻前 169 类缓存 ---------------- */
  /* ---------------- Preflop 169-class cache ---------------- */
  const preflopCache = new Map();

  function preflopEquity(key, nOpp) {
    const ck = key + '|' + nOpp;
    const hit = preflopCache.get(ck);
    if (hit !== undefined) return hit;
    const eq = estimateEquity(PK.holeFromKey(key), [], nOpp, 2500);
    preflopCache.set(ck, eq);
    return eq;
  }

  /** 预热常用对手数量的翻前表（后台分片执行，避免首手卡顿） */
  /** Warm up the preflop table for common opponent counts (run in background slices to avoid a stall on the first hand) */
  function warmupPreflop(nOppList) {
    const keys = HAND_RANK_ORDER;
    let k = 0, o = 0;
    function step() {
      const t0 = Date.now();
      while (k < keys.length && Date.now() - t0 < 12) {
        preflopEquity(keys[k], nOppList[o]);
        k++;
      }
      if (k >= keys.length) {
        o++;
        k = 0;
        if (o >= nOppList.length) return;
      }
      setTimeout(step, 0);
    }
    setTimeout(step, 0);
  }

  /** 统一入口：翻前走缓存表，翻后实时蒙特卡洛 */
  /** Unified entry: preflop uses the cached table, postflop runs live Monte Carlo */
  function equity(hole, board, nOpp, iters, rangePct) {
    if (!board || board.length === 0) {
      return preflopEquity(PK.holeKey(hole[0], hole[1]), nOpp);
    }
    return estimateEquity(hole, board, nOpp, iters || 1500, rangePct);
  }

  /** 异步包装：把计算推到下一轮事件循环，先让界面刷新 */
  /** Async wrapper: defer the computation to the next event-loop turn so the UI can refresh first */
  function equityAsync(hole, board, nOpp, iters, rangePct) {
    return new Promise(function (resolve) {
      setTimeout(function () {
        resolve(equity(hole, board, nOpp, iters, rangePct));
      }, 0);
    });
  }

  PK.HAND_RANK_ORDER = HAND_RANK_ORDER;
  PK.pct2 = pct2;
  PK.handPercentile = handPercentile;
  PK.estimateEquity = estimateEquity;
  PK.preflopEquity = preflopEquity;
  PK.warmupPreflop = warmupPreflop;
  PK.equity = equity;
  PK.equityAsync = equityAsync;

  if (typeof module !== 'undefined' && module.exports) module.exports = PK;
})(typeof globalThis !== 'undefined' ? globalThis : this);
